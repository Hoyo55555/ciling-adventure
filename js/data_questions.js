function normCat(c, q) {
  c = String(c || '').trim(); if (!c) return '閱讀';
  if (c === '字音字形') return /讀音|讀作|注音|[ㄅ-ㄩ]/.test(q || '') ? '字音' : '字形';
  return CAT_ALIAS[c] || c;
}
function qid(q) { const s = (q.q || '') + '|' + (q.opts || q.parts || []).join('|'); let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0; return 'q' + h.toString(36); }
function normalizeQ(q) {
  const o = Object.assign({}, q);
  o.type = o.type || (o.parts ? 'order' : (typeof o.ans === 'boolean' ? 'tf' : (o.opts ? 'choice' : 'fill')));
  o.cat = normCat(o.cat, o.q); o.lv = clamp(+o.lv || 1, 1, 3); o.lesson = String(o.lesson || '').trim();
  if (o.type === 'fill' && !Array.isArray(o.ans)) o.ans = String(o.ans || '').split(/[\/／|]/).map(s => s.trim()).filter(Boolean);
  o.id = o.id || qid(o); return o;
}

